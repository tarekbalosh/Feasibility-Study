export const MAX_CUSTOM_ITEM_LENGTH = 60

/** يظهر حقل البحث فقط إذا تجاوزت القائمة هذا العدد */
export const SEARCH_VISIBILITY_THRESHOLD = 15

/**
 * العدد المُوصى به من البنود المختارة في كل مجموعة — استشاري لا يمنع
 * التجاوز، فقط ينبّه المستخدم أن تحليلاً أدق يتطلّب تركيزاً أكثر.
 */
export const RECOMMENDED_MAX_SELECTIONS = 4

/**
 * تطبيع نص للمقارنة: إزالة التشكيل والتطويل، وتوحيد الهمزات والألف
 * المقصورة والتاء المربوطة، وضغط المسافات — حتى لا يُقبل «تمويلٌ قوي»
 * تكراراً لـ «تمويل قوي».
 */
export const normalizeArabic = (value: string): string =>
  value
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[ؤ]/g, "و")
    .replace(/[ئ]/g, "ي")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()

/**
 * فهرس الشروح بنصّ البند لا بمعرّفه: الخادم يستقبل الاختيارات نصوصاً
 * (SwotSelectionPayload) لا معرّفات، فيحتاج البحث بالنص المطبَّع.
 */
const detailByLabel: Record<string, string> = SWOT_CATEGORY_ORDER.reduce(
  (acc, category) => {
    for (const suggestion of swotSuggestions[category]) {
      if (suggestion.detail) acc[normalizeArabic(suggestion.label)] = suggestion.detail
    }
    return acc
  },
  {} as Record<string, string>
)

/** الشرح الافتراضي لبند جاهز بنصّه — undefined للبنود المخصّصة */
export const suggestionDetail = (label: string): string | undefined =>
  detailByLabel[normalizeArabic(label)]
