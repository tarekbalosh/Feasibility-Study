/** ترقيم ثابت بخانتين: str-01 … str-24 */
const seq = (prefix: string, index: number): string =>
  `${prefix}-${String(index + 1).padStart(2, "0")}`

const buildList = (prefix: string, seeds: Seed[]): SwotSuggestion[] =>
  seeds.map((seed, index) => ({
    id: seq(prefix, index),
    label: seed.label,
    detail: seed.detail,
  }))

export const swotSuggestions: Record<SwotCategory, SwotSuggestion[]> = {
  strengths: STRENGTH_WEAKNESS_PAIRS.map(([strength], index) => ({
    id: seq("str", index),
    label: strength.label,
    detail: strength.detail,
    pairId: seq("wea", index),
  })),
  weaknesses: STRENGTH_WEAKNESS_PAIRS.map(([, weakness], index) => ({
    id: seq("wea", index),
    label: weakness.label,
    detail: weakness.detail,
    pairId: seq("str", index),
  })),
  opportunities: buildList("opp", OPPORTUNITY_SEEDS),
  threats: buildList("thr", THREAT_SEEDS),
}

/** ترتيب العرض — يطابق ترتيب المصفوفة النهائية */
export const SWOT_CATEGORY_ORDER: SwotCategory[] = [
  "strengths",
  "weaknesses",
  "opportunities",
  "threats",
]

/** فهرس مسطّح للوصول إلى أي بند جاهز بمعرّفه دون بحث خطّي */
export const swotSuggestionIndex: Record<string, SwotSuggestion> =
  SWOT_CATEGORY_ORDER.reduce((acc, category) => {
    for (const suggestion of swotSuggestions[category]) {
      acc[suggestion.id] = suggestion
    }
    return acc
  }, {} as Record<string, SwotSuggestion>)

